// Color pixel-art toolbar icons (Batch 12): the Standard icons
// are small COLOR bitmap glyphs (Word 95), not monochrome line
// art. Each Standard icon is a 16x16 map of palette keys
// (generated by /tmp/icon_gen.py from coordinate primitives;
// the maps are data, the palette is the code). Drawn with
// per-pixel rects inside the existing on_draw_fg render-pass
// path — no textures, no new files. Cost: at most 256 rects
// per button, only for the visible toolbar.
//
// Palette keys:
//   '.' transparent · W white · K black (outline) · G dark gray
//   g light gray · D (unused) · Y folder yellow #FFD83D ·
//   y dark yellow · O orange · o brown · B blue · b light blue
//   R red · r (unused) · S steel · T tan (clipboard)
// Disabled: every palette color is swapped for a flat gray in
// the same luminance band (96..192), so a disabled icon reads
// grayed-out instead of colorful.
namespace toolbar_icons_detail {

struct IconPixel {
    char key;
    afterhours::Color color;
};

inline constexpr IconPixel kIconPalette[] = {
    {'W', afterhours::Color{255, 255, 255, 255}},
    {'K', afterhours::Color{0, 0, 0, 255}},
    {'G', afterhours::Color{128, 128, 128, 255}},
    {'g', afterhours::Color{192, 192, 192, 255}},
    {'Y', afterhours::Color{255, 216, 61, 255}},
    {'y', afterhours::Color{224, 168, 0, 255}},
    {'O', afterhours::Color{255, 128, 0, 255}},
    {'o', afterhours::Color{160, 82, 45, 255}},
    {'B', afterhours::Color{36, 86, 216, 255}},
    {'b', afterhours::Color{111, 168, 255, 255}},
    {'R', afterhours::Color{255, 0, 0, 255}},
    {'S', afterhours::Color{88, 98, 112, 255}},
    {'T', afterhours::Color{210, 180, 120, 255}},
};

inline afterhours::Color iconPixelColor(char key, bool enabled) {
    for (const auto& entry : kIconPalette) {
        if (entry.key != key) continue;
        if (enabled) return entry.color;
        // Desaturate to a flat gray: luminance mapped into
        // 96..192 (white paper goes pale gray, black goes dark
        // gray — nothing stays colorful).
        int lum = (static_cast<int>(entry.color.r) * 299 +
                   static_cast<int>(entry.color.g) * 587 +
                   static_cast<int>(entry.color.b) * 114) / 1000;
        auto v = static_cast<unsigned char>(96 + (lum * 96) / 255);
        return afterhours::Color{v, v, v, entry.color.a};
    }
    return afterhours::Color{0, 0, 0, 0};
}

// Draw a 16x16 palette map into (x0, y0, iw, ih): float pixel
// rects (a 0.01 overlap keeps hairline gaps from opening
// between abutting pixels). Integer-rounded edges were tried
// first: at the toolbar's ~14px icon size the 16-pixel grid is
// sub-pixel, so rounding dropped whole columns (the Spelling
// ABC lost strokes).
inline void drawPixelMap(const char* const rows[16], float x0, float y0,
                         float iw, float ih, bool enabled) {
    float pw = iw / 16.0f;
    float ph = ih / 16.0f;
    for (int row = 0; row < 16; ++row) {
        for (int col = 0; col < 16; ++col) {
            char key = rows[row][col];
            if (key == '.') continue;
            afterhours::Color color = iconPixelColor(key, enabled);
            afterhours::draw_rectangle(
                Rectangle{x0 + static_cast<float>(col) * pw,
                          y0 + static_cast<float>(row) * ph, pw + 0.01f,
                          ph + 0.01f},
                color);
        }
    }
}

}  // namespace toolbar_icons_detail

